#!/usr/bin/env python3
"""Generates the single-file nginx-h2-probe.py from the package sources,
so there is exactly one source of truth. Run from the repo root:

    python3 scripts/build_standalone.py

CI verifies the committed standalone matches (see .github/workflows/ci.yml).
"""

import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src", "nginx_h2_probe")
OUT = os.path.join(ROOT, "nginx-h2-probe.py")

ORDER = ["core.py", "local.py", "server.py", "cli.py"]

HEADER = '''#!/usr/bin/env python3
"""
nginx-h2-probe -- safe, reliable exposure check for the 2026 nginx
HTTP/2 RCEs (CVE-2026-123007, CVE-2026-123633).

Single-file build (generated by scripts/build_standalone.py from the
same sources as the pip package). Zero dependencies: stock Python 3.8+.

    ./nginx-h2-probe.py check example.com          # definitive (1-8 min)
    ./nginx-h2-probe.py check example.com --passive  # instant triage
    ./nginx-h2-probe.py local                       # on-the-host checks
    ./nginx-h2-probe.py serve --token SECRET        # curl-friendly mode

Exit codes: 0 not vulnerable / not exposed, 1 vulnerable,
2 inconclusive, 3 error. Run only against systems you are authorized
to test. The active test is safe by design: it never creates the
oversized-window state needed for memory corruption (see the README).
"""

'''


def main():
    parts = [HEADER]
    for name in ORDER:
        path = os.path.join(SRC, name)
        with open(path, encoding="utf-8") as f:
            text = f.read()
        # strip the module docstring (the standalone has one header doc)
        if text.startswith('"""'):
            end = text.find('"""', 3)
            text = text[end + 3:].lstrip("\n")
        # strip intra-package imports: after concatenation all names are
        # module-level and already defined by earlier sections
        lines = [line for line in text.splitlines()
                 if "from nginx_h2_probe" not in line]
        parts.append(("# " + "-" * 75 + "\n"
                      "# %s (from src/nginx_h2_probe/%s)\n" % (name, name) +
                      "# " + "-" * 75 + "\n\n"))
        parts.append("\n".join(lines).rstrip() + "\n\n")

    out = "".join(parts)
    # sanity: concatenation must not have left package-qualified references
    leftover = re.findall(r"nginx_h2_probe\.\w+", out)
    if leftover:
        raise SystemExit("standalone build failed, unresolved package "
                         "references: %s" % sorted(set(leftover)))

    with open(OUT, "w", encoding="utf-8") as f:
        f.write(out)
    os.chmod(OUT, 0o755)
    print("wrote %s (%d bytes)" % (OUT, len(out)))


if __name__ == "__main__":
    main()